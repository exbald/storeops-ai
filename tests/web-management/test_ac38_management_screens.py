def test_ac38_contract_conformance_for_management_requests():
    """Verify that request objects generated by web client conform strictly to OpenAPI models."""
    # Store creation request
    store_req = StoreCreate(
        code="STR-001",
        name="Marina Bay Supermarket",
        retailer="ColdStorage",
        format="HYPERMARKET",
        region="South",
        timezone="Asia/Singapore",
        distributor_location_id=None,
    )
    dumped = store_req.model_dump(mode="json")
    assert dumped["name"] == "Marina Bay Supermarket"
    assert dumped["timezone"] == "Asia/Singapore"

    # Store update with expected_version (required for conflict detection)
    store_update = StoreUpdate(
        name="Marina Bay Supermarket - North Wing",
        active=True,
        timezone="Asia/Singapore",
        expected_version=1,
    )
    assert store_update.expected_version == 1

    # Product creation request
    prod_req = ProductCreate(
        sku="BEV-SPRITE-330",
        name="Sprite 330ml Can",
        case_units=24,
    )
    assert prod_req.case_units == 24

    # Promotion approval request with valid Rule models
    approve_req = ApprovePolicy(
        expected_version=1,
        catalog_product_ids=["33333333-3333-3333-3333-333333333333"],
        rules=[
            Rule(
                rule_id="aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa",
                kind=Kind5.MIN_FACINGS,
                zone_id="shelf-main",
                zone_kind=ZoneKind.SHELF,
                product_id="33333333-3333-3333-3333-333333333333",
                min_facings=3,
                source=PolicySource(
                    kind=Kind4.DOCUMENT,
                    media_id="bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb",
                    page=1,
                    quote="Maintain at least 3 facings on primary shelf.",
                    reviewer_note=None,
                ),
            )
        ],
    )
    assert len(approve_req.rules) == 1
    assert approve_req.rules[0].min_facings == 3



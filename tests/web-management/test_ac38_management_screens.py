def test_ac38_accessible_controls_and_responsive_markup():
    """Verify that web components follow accessibility guidelines and lack fixed overflow widths.
    
    From specs/04-ui.md:
    - At 375 px and desktop widths, the main flow has no horizontal page overflow.
    - Inputs have labels, focus states, keyboard operation and text equivalents for status colors.
    """
    components_dir = WEB_SRC_DIR / "components"
    assert components_dir.exists(), "apps/web/src/components must exist"

    # Inspect all TSX files in components
    tsx_files = list(components_dir.glob("**/*.tsx"))
    assert len(tsx_files) > 0, "There should be component files in apps/web/src/components"

    combined_code = "\n".join(f.read_text(encoding="utf-8") for f in tsx_files)

    # Check for accessibility patterns
    has_labels_or_aria = "aria-label" in combined_code or "htmlFor" in combined_code
    assert has_labels_or_aria, "Components must use aria-label or htmlFor for input associations"

    has_sr_only_or_aria = "sr-only" in combined_code or "aria-live" in combined_code or "role=" in combined_code
    assert has_sr_only_or_aria, "Components must provide text equivalents for visual/status indicators"


